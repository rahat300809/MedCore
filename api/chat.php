<?php
/**
 * MedCore Groq Chatbot API Endpoint
 * Handles conversational queries, doctor triage recommendations, and direct booking actions.
 */

// Enable session
if (session_status() === PHP_SESSION_NONE) {
    session_start();
}

header('Content-Type: application/json; charset=utf-8');

// Require dependencies with flexible pathing for Vercel / serverless
if (file_exists(__DIR__ . '/../app/services/ChatbotService.php')) {
    require_once __DIR__ . '/../app/services/ChatbotService.php';
} else {
    require_once __DIR__ . '/../../app/services/ChatbotService.php';
}

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    echo json_encode([
        'success' => false,
        'message' => 'Only POST requests are supported.'
    ]);
    exit;
}

// Read raw JSON or form post
$rawBody = file_get_contents('php://input');
$inputData = json_decode($rawBody, true) ?: $_POST;

$messages = $inputData['messages'] ?? [];
$singleMessage = trim($inputData['message'] ?? '');

if (empty($messages) && !empty($singleMessage)) {
    $messages = [
        ['role' => 'user', 'content' => $singleMessage]
    ];
}

if (empty($messages)) {
    echo json_encode([
        'success' => false,
        'message' => 'No message content provided.'
    ]);
    exit;
}

// Execute AI Chatbot processing
$response = ChatbotService::chat($messages);

if (!$response['success']) {
    echo json_encode([
        'success' => false,
        'message' => $response['message'] ?? 'Unable to connect to AI assistant. Please try again.'
    ]);
    exit;
}

$replyText = $response['reply'];
$isLoggedIn = isset($_SESSION['role']) && $_SESSION['role'] === 'PATIENT';
$patientName = $_SESSION['name'] ?? null;
$patientUid  = $_SESSION['patient_uid'] ?? null;

// Parse [BOOK_DOCTOR: doc_id, hosp_id, doc_name] tags if generated by AI
$actionCards = [];
if (preg_match_all('/\[BOOK_DOCTOR:\s*(\d+),\s*(\d+),\s*([^\]]+)\]/i', $replyText, $matches, PREG_SET_ORDER)) {
    foreach ($matches as $m) {
        $docId   = (int)$m[1];
        $hospId  = (int)$m[2];
        $docName = trim($m[3]);
        
        $actionCards[] = [
            'type'        => 'doctor_booking',
            'doctor_id'   => $docId,
            'hospital_id' => $hospId,
            'doctor_name' => $docName,
            'is_logged_in'=> $isLoggedIn,
            'booking_url' => APP_URL . "/book-doctor.php?doctor_id={$docId}&hospital={$hospId}",
            'login_url'   => APP_URL . "/patient/login.php?redirect=" . urlencode("/book-doctor.php?doctor_id={$docId}&hospital={$hospId}"),
            'register_url'=> APP_URL . "/patient/register.php"
        ];
    }
    // Remove the raw tag from the user-facing text
    $replyText = preg_replace('/\[BOOK_DOCTOR:\s*\d+,\s*\d+,\s*[^\]]+\]/i', '', $replyText);
    $replyText = trim($replyText);
}

echo json_encode([
    'success'      => true,
    'reply'        => $replyText,
    'is_logged_in' => $isLoggedIn,
    'patient_name' => $patientName,
    'patient_uid'  => $patientUid,
    'action_cards' => $actionCards
], JSON_UNESCAPED_UNICODE);

